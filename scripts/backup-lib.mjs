// Shared by backup.mjs and restore.mjs: export and import the tracker tables, and encrypt the backup file.
// Encryption: AES-256-GCM with a key derived from your passphrase by scrypt (N=2^17, r=8, p=1, 16-byte salt).
// The file holds only the salt, IV, tag and ciphertext; without the passphrase it can't be read or changed.

import { scryptSync, randomBytes, createCipheriv, createDecipheriv } from "node:crypto";
import { homedir } from "node:os";
import { join, resolve, relative, isAbsolute, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const TABLES = ["profiles", "deals", "bankers", "notes", "history", "settings"];
export const FORMAT = "ascot-deal-desk-backup";
const KDF = { N: 2 ** 17, r: 8, p: 1, maxmem: 256 * 1024 * 1024 };
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_DIR = join(homedir(), "Documents", "ascot-deal-desk-backups");

export function encrypt(obj, passphrase) {
  const salt = randomBytes(16), iv = randomBytes(12);
  const key = scryptSync(passphrase, salt, 32, KDF);
  const c = createCipheriv("aes-256-gcm", key, iv);
  const data = Buffer.concat([c.update(JSON.stringify(obj), "utf8"), c.final()]);
  return JSON.stringify({ format: FORMAT, v: 1, kdf: "scrypt", N: KDF.N, r: KDF.r, p: KDF.p,
    salt: salt.toString("base64"), iv: iv.toString("base64"), tag: c.getAuthTag().toString("base64"), data: data.toString("base64") }) + "\n";
}

export function decrypt(text, passphrase) {
  let f;
  try { f = JSON.parse(text); } catch { throw new Error("This isn't a deal desk backup file."); }
  if (f.format !== FORMAT || f.v !== 1) throw new Error("This isn't a deal desk backup file (or it's from a newer version).");
  const key = scryptSync(passphrase, Buffer.from(f.salt, "base64"), 32, { N: f.N, r: f.r, p: f.p, maxmem: KDF.maxmem });
  const d = createDecipheriv("aes-256-gcm", key, Buffer.from(f.iv, "base64"));
  d.setAuthTag(Buffer.from(f.tag, "base64"));
  try { return JSON.parse(Buffer.concat([d.update(Buffer.from(f.data, "base64")), d.final()]).toString("utf8")); }
  catch { throw new Error("Wrong passphrase, or the file has been changed."); }
}

/** Refuse to write backups inside the repository folder (it's public on GitHub). */
export function checkOutDir(dir) {
  const abs = resolve(dir), rel = relative(REPO_ROOT, abs);
  if (rel === "" || (!rel.startsWith("..") && !isAbsolute(rel))) throw new Error(`Backups can't go inside the repository folder (${REPO_ROOT}): it's published on GitHub. Choose a folder outside it.`);
  return abs;
}

const missing = (e) => e && (e.code === "PGRST205" || e.code === "42P01" || /does not exist|schema cache/i.test(e.message || ""));

/** Read every row of each table, 1,000 at a time. Tables that don't exist yet (history, settings) are skipped. */
export async function dump(sb, tables = TABLES) {
  const out = {}, skipped = [];
  for (const t of tables) {
    const rows = [];
    for (let from = 0; ; from += 1000) {
      const { data, error } = await sb.from(t).select("*").order("id", { ascending: true }).range(from, from + 999);
      if (error) { if (missing(error) && !rows.length) { skipped.push(t); break; } throw new Error(`Couldn't read ${t}: ${error.message}`); }
      rows.push(...(data || []));
      if (!data || data.length < 1000) break;
    }
    if (!skipped.includes(t)) out[t] = rows;
  }
  return { tables: out, skipped };
}

/** Tables a restore writes back. History is kept in the backup as a record but not written back: it is the
    audit log (append-only, ids generated by the database), so a restore adds its own entries instead. */
export const RESTORE_TABLES = TABLES.filter((t) => t !== "history");

/** Upsert rows by id, 500 at a time, in the order of RESTORE_TABLES. Returns counts and any table errors. */
export async function restore(sb, tables) {
  const done = {}, errors = {};
  for (const t of RESTORE_TABLES) {
    const rows = tables[t]; if (!rows || !rows.length) continue;
    done[t] = 0;
    for (let i = 0; i < rows.length; i += 500) {
      const { error } = await sb.from(t).upsert(rows.slice(i, i + 500), { onConflict: "id" });
      if (error) { errors[t] = error.message; break; }
      done[t] += Math.min(500, rows.length - i);
    }
  }
  return { done, errors };
}

export const counts = (tables) => Object.fromEntries(Object.entries(tables).map(([t, r]) => [t, r.length]));
export const stamp = (d = new Date()) => d.toISOString().slice(0, 16).replace("T", "-").replace(":", "");
